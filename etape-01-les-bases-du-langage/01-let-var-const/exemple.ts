// 1. const : la valeur ne peut pas changer
const prenom: string = "Aita";

// 2. let : la valeur peut changer
let age: number = 20;
age = 21;

// 3. var : ancienne façon de déclarer une variable
var ville: string = "Dakar";
ville = "Thiès";

console.log("Prénom :", prenom);
console.log("Âge :", age);
console.log("Ville :", ville);
